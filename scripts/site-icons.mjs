// Builds site/assets/icons.svg, an SVG sprite of the Lucide icons (ISC) the website uses.
// Usage: node scripts/site-icons.mjs
import { writeFileSync } from 'node:fs'

const ICONS = [
  'gamepad-2',
  'app-window',
  'keyboard-off',
  'mouse-pointer-ban',
  'crosshair',
  'tv',
  'volume-2',
  'users',
  'shield-check',
  'gauge',
  'library',
  'bookmark',
  'clock',
  'hard-drive-download',
  'sun-moon',
  'languages',
  'download',
  'code-xml',
  'arrow-right',
  'check',
  'zap',
  'eye-off',
  'monitor-speaker',
  'octagon-x',
  'chevron-down',
  'x',
  'circle-play',
  'bug',
  'refresh-cw',
  'layers',
  'sparkles',
  'lock',
  'play',
  'monitor',
  'pause',
  'circle-x',
  'activity',
  'bell',
]

const attrs = (props) =>
  Object.entries(props)
    .filter(([key]) => key !== 'key')
    .map(([key, value]) => `${key}="${value}"`)
    .join(' ')

const symbols = []
for (const name of ICONS) {
  const { __iconData } = await import(`@lucide/vue/dist/esm/icons/${name}.mjs`)
  const body = __iconData.node.map(([tag, props]) => `<${tag} ${attrs(props)}/>`).join('')
  symbols.push(`<symbol id="${name}" viewBox="0 0 24 24">${body}</symbol>`)
}

const sprite =
  '<!-- Lucide icons (https://lucide.dev), ISC License. Generated by scripts/site-icons.mjs. -->\n' +
  '<svg xmlns="http://www.w3.org/2000/svg" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round">\n' +
  symbols.join('\n') +
  '\n</svg>\n'
writeFileSync(new URL('../site/assets/icons.svg', import.meta.url), sprite)
console.log(`site/assets/icons.svg: ${ICONS.length} icons`)
